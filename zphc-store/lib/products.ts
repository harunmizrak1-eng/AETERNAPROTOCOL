export function getProduct(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug)
}

export function productsByCategory(category: ProductCategory): Product[] {
  return products.filter((p) => p.category === category)
}

/** Aynı bileşiğin diğer boy/sunum varyantları. */
export function variantsOf(product: Product): Product[] {
  return products.filter(
    (p) => p.compound === product.compound && p.slug !== product.slug,
  )
}
